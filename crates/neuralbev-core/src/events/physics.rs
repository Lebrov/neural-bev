//! # events::physics
//!
//! Физические события: коллизии, триггеры.
//!
//! ## AI-HINT
//! Эти события приходят от физического движка (Rapier) через адаптер.
//! Подписывайся на них вместо проверок Transform вручную.

use bevy::prelude::*;

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Начало контакта двух физических тел.  
/// WHY:  Основное событие для обработки коллизий (урон, звук, отскок).  
/// HOW:  ```rust
///       fn on_collision(mut ev: EventReader<CollisionStarted>, tags: Query<&Tags>) {
///           for c in ev.read() {
///               if let Ok(tags) = tags.get(c.other) {
///                   if tags.has("enemy") { /* ... */ }
///               }
///           }
///       }
///       ```
/// AI-HINT: `entity` — та сущность, на которую повешен listener; `other` — вторая.
#[derive(Event, Debug, Clone)]
pub struct CollisionStarted {
    /// Первая сущность столкновения.
    pub entity: Entity,
    /// Вторая сущность столкновения.
    pub other: Entity,
    /// Нормаль контакта (из физического движка).
    pub normal: Vec3,
}

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Конец контакта двух физических тел.  
/// WHY:  Позволяет отслеживать, когда сущности перестают соприкасаться.  
/// AI-HINT: Используй для деактивации эффектов (например, стоп-звук трения).
#[derive(Event, Debug, Clone)]
pub struct CollisionEnded {
    /// Первая сущность.
    pub entity: Entity,
    /// Вторая сущность.
    pub other: Entity,
}
