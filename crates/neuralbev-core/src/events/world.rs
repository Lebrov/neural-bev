//! # events::world
//!
//! События жизненного цикла мира и сущностей.
//!
//! ## AI-HINT
//! Подписывайся на эти события для реакции на загрузку/выгрузку сцен
//! и создание/уничтожение сущностей.

use bevy::prelude::*;

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Событие успешной загрузки сцены.  
/// WHY:  Позволяет системам реагировать на переход между сценами.  
/// HOW:  ```rust
///       fn on_scene_loaded(mut ev: EventReader<SceneLoaded>) {
///           for ev in ev.read() {
///               info!("Сцена загружена: {}", ev.scene_name);
///           }
///       }
///       ```
/// AI-HINT: Слушай это событие для инициализации игровых систем после загрузки.
#[derive(Event, Debug, Clone)]
pub struct SceneLoaded {
    /// Имя загруженной сцены (из поля `meta.scene_name` в YAML).
    pub scene_name: String,
    /// Путь к файлу сцены (относительно assets/).
    pub path: String,
}

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Событие выгрузки сцены.  
/// WHY:  Даёт системам шанс очиститься перед сменой сцены.  
/// AI-HINT: Слушай для освобождения ресурсов и сохранения прогресса.
#[derive(Event, Debug, Clone)]
pub struct SceneUnloaded {
    /// Имя выгруженной сцены.
    pub scene_name: String,
}

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Событие спауна сущности через Blueprint-систему.  
/// WHY:  Позволяет другим системам реагировать на появление новых сущностей.  
/// HOW:  ```rust
///       fn on_entity_spawned(mut ev: EventReader<EntitySpawned>) {
///           for ev in ev.read() {
///               println!("Создана: {} ({:?})", ev.name, ev.entity);
///           }
///       }
///       ```
/// AI-HINT: Это событие приходит ПОСЛЕ того, как сущность добавлена в World.
#[derive(Event, Debug, Clone)]
pub struct EntitySpawned {
    /// Созданная сущность.
    pub entity: Entity,
    /// Имя сущности (из EntityName компонента или Blueprint).
    pub name: String,
}

// ──────────────────────────────────────────────────────────────────────────────

/// WHAT: Событие деспауна сущности.  
/// WHY:  Позволяет очистить связанные данные (инвентарь, AI-состояние, …).  
/// AI-HINT: Entity уже невалиден к моменту получения события.
#[derive(Event, Debug, Clone)]
pub struct EntityDespawned {
    /// Сущность, которая была уничтожена (невалидна).
    pub entity: Entity,
    /// Имя на момент уничтожения.
    pub name: String,
}
